import { describe, it, expect } from 'vitest';
import { createRequire } from 'node:module';
import * as nodeCrypto from 'node:crypto';
import { decryptPayload, parseHeaderParam } from '../../src/core/ece.js';
import { fromBase64Url, decodeUtf8Strict, toBase64Url } from '../../src/core/bytes.js';
import { generateKeys } from '../../src/core/keys.js';
import { DecryptionError } from '../../src/core/errors.js';

const require = createRequire(import.meta.url);
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const httpEce = require('http_ece') as any;

describe('ece module', () => {
  describe('parseHeaderParam', () => {
    it('should parse single parameter', () => {
      expect(parseHeaderParam('dh=my_dh_key', 'dh')).toBe('my_dh_key');
    });

    it('should parse multiple semicolon-delimited parameters with whitespace', () => {
      const header = ' dh=abc123 ; p256ecdsa=xyz789; foo=bar ';
      expect(parseHeaderParam(header, 'dh')).toBe('abc123');
      expect(parseHeaderParam(header, 'p256ecdsa')).toBe('xyz789');
      expect(parseHeaderParam(header, 'foo')).toBe('bar');
    });

    it('should throw DecryptionError if header is missing or param is not found', () => {
      expect(() => parseHeaderParam(undefined, 'dh')).toThrow(DecryptionError);
      expect(() => parseHeaderParam('p256ecdsa=xyz', 'dh')).toThrow(DecryptionError);
    });
  });

  describe('RFC 8291 Section 5 / Appendix A official vector', () => {
    it('should decrypt official RFC 8291 aes128gcm vector', async () => {
      // Plaintext: "When I grow up, I want to be a watermelon"
      const body = fromBase64Url(`
        DGv6ra1nlYgDCS1FRnbzlwAAEABBBP4z9KsN6nGRTbVYI_c7VJSPQTBtkgcy27ml
        mlMoZIIgDll6e3vCYLocInmYWAmS6TlzAC8wEqKK6PBru3jl7A_yl95bQpu6cVPT
        pK4Mqgkf1CXztLVBSt2Ks3oZwbuwXPXLWyouBWLVWGNWQexSgSxsj_Qulcy4a-fN
      `);

      const keys = {
        privateKey: fromBase64Url('q1dXpw3UpT5VOmu_cf_v6ih07Aems3njxI-JWgLcM94'),
        publicKey: fromBase64Url(
          'BCVxsr7N_eNgVRqvHtD0zTZsEc6-VV-JvLexhqUzORcxaOzi6-AYWXvTBHm4bjyPjs7Vd8pZGH6SRpkNtoIAiw4'
        ),
        authSecret: fromBase64Url('BTBZMqHH6r4Tts7J_aSIgg'),
      };

      const decrypted = await decryptPayload(body, { encoding: 'aes128gcm' }, keys);
      expect(decodeUtf8Strict(decrypted)).toBe('When I grow up, I want to be a watermelon');

      // Also should work when encoding is omitted (default is aes128gcm)
      const decryptedDefault = await decryptPayload(body, undefined, keys);
      expect(decodeUtf8Strict(decryptedDefault)).toBe('When I grow up, I want to be a watermelon');
    });

    it('should reject tampered ciphertext', async () => {
      const body = fromBase64Url(`
        DGv6ra1nlYgDCS1FRnbzlwAAEABBBP4z9KsN6nGRTbVYI_c7VJSPQTBtkgcy27ml
        mlMoZIIgDll6e3vCYLocInmYWAmS6TlzAC8wEqKK6PBru3jl7A_yl95bQpu6cVPT
        pK4Mqgkf1CXztLVBSt2Ks3oZwbuwXPXLWyouBWLVWGNWQexSgSxsj_Qulcy4a-fN
      `);
      body[body.length - 1] ^= 0x01; // flip last bit

      const keys = {
        privateKey: fromBase64Url('q1dXpw3UpT5VOmu_cf_v6ih07Aems3njxI-JWgLcM94'),
        publicKey: fromBase64Url(
          'BCVxsr7N_eNgVRqvHtD0zTZsEc6-VV-JvLexhqUzORcxaOzi6-AYWXvTBHm4bjyPjs7Vd8pZGH6SRpkNtoIAiw4'
        ),
        authSecret: fromBase64Url('BTBZMqHH6r4Tts7J_aSIgg'),
      };

      await expect(decryptPayload(body, { encoding: 'aes128gcm' }, keys)).rejects.toThrow(
        DecryptionError
      );
    });
  });

  describe('cross-verification with http_ece', () => {
    it('should decrypt aes128gcm generated by http_ece', async () => {
      const keys = await generateKeys();
      const message = JSON.stringify({
        title: 'テスト通知',
        text: 'こんにちは世界！',
        url: 'https://x.com',
      });

      const sender = nodeCrypto.createECDH('prime256v1');
      sender.generateKeys();
      const salt = nodeCrypto.randomBytes(16);

      const encrypted = httpEce.encrypt(Buffer.from(message, 'utf-8'), {
        version: 'aes128gcm',
        privateKey: sender,
        dh: Buffer.from(keys.publicKey),
        salt,
        authSecret: Buffer.from(keys.authSecret),
      });

      const decrypted = await decryptPayload(
        new Uint8Array(encrypted),
        { encoding: 'aes128gcm' },
        keys
      );
      expect(decodeUtf8Strict(decrypted)).toBe(message);
    });

    it('should decrypt multi-record aes128gcm (small rs)', async () => {
      const keys = await generateKeys();
      const longMessage = 'A'.repeat(5000);

      const sender = nodeCrypto.createECDH('prime256v1');
      sender.generateKeys();
      const salt = nodeCrypto.randomBytes(16);

      const encrypted = httpEce.encrypt(Buffer.from(longMessage, 'utf-8'), {
        version: 'aes128gcm',
        privateKey: sender,
        dh: Buffer.from(keys.publicKey),
        salt,
        authSecret: Buffer.from(keys.authSecret),
        rs: 256,
      });

      const decrypted = await decryptPayload(
        new Uint8Array(encrypted),
        { encoding: 'aes128gcm' },
        keys
      );
      expect(decodeUtf8Strict(decrypted)).toBe(longMessage);
    });

    it('should decrypt legacy aesgcm generated by http_ece', async () => {
      const keys = await generateKeys();
      const message = JSON.stringify({ event: 'tweet', user: 'elonmusk' });

      const sender = nodeCrypto.createECDH('prime256v1');
      sender.generateKeys();
      const salt = nodeCrypto.randomBytes(16);

      const encrypted = httpEce.encrypt(Buffer.from(message, 'utf-8'), {
        version: 'aesgcm',
        privateKey: sender,
        dh: Buffer.from(keys.publicKey),
        salt,
        authSecret: Buffer.from(keys.authSecret),
        pad: 15,
      });

      const headers = {
        encoding: 'aesgcm',
        crypto_key: `dh=${toBase64Url(new Uint8Array(sender.getPublicKey()))}`,
        encryption: `salt=${toBase64Url(new Uint8Array(salt))}`,
      };

      const decrypted = await decryptPayload(new Uint8Array(encrypted), headers, keys);
      expect(decodeUtf8Strict(decrypted)).toBe(message);
    });

    it('should reject unsupported encoding', async () => {
      const keys = await generateKeys();
      await expect(
        decryptPayload(new Uint8Array([1, 2, 3]), { encoding: 'deflate' }, keys)
      ).rejects.toThrow(DecryptionError);
    });
  });
});
